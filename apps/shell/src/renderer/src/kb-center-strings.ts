import type { Lang } from '@genoffice/i18n'

/**
 * The Knowledge Base center's words (知识库), owned by the view itself — one
 * entry per UI language, the same single-file shape as desktop-strings.ts:
 * the center is a Home surface like the desktop, not a strings/ dictionary
 * consumer, and its copy is all it carries. zh/zh-TW/en are natural copy;
 * the rest are best-effort translations of the same meaning.
 */
export interface KbCenterStrings {
  /** the desktop tile / view's name */
  title: string
  /** the header's one-line "what this is": the AI answers from these sources */
  intro: string
  /** the sources section's heading */
  sourcesTitle: string
  /** the pipeline banner while a scan runs ({n} = pending files) */
  scanning: string
  /** the entry cap cut the file list */
  truncated: string
  /** a source's readiness labels */
  statusReady: string
  statusIndexing: string
  statusError: string
  statusEmpty: string
  /** a folder source's indexed/errors counts ({i} / {e}) */
  countsFolder: string
  /** add-folder verb (the existing folder-root picker) */
  addFolder: string
  /** add-files verb (the star-onboarding picker) */
  addFiles: string
  /** remove verb per source */
  remove: string
  /** remove's confirm for a folder root ({name}) */
  confirmRemoveFolder: string
  /** remove's confirm for a file source ({name}) */
  confirmRemoveFile: string
  /** reindex verb per source + the global one */
  reindex: string
  reindexAll: string
  /** the sources list's empty state (no folder root, nothing indexed) */
  sourcesEmpty: string
  /** the recall-test section's heading */
  recallTitle: string
  /** the recall-test input's placeholder */
  recallPlaceholder: string
  /** the recall-test submit button */
  recallRun: string
  /** the recall-test result line ({n} hits) */
  recallHits: string
  /** the recall-test's no-hit answer */
  recallNone: string
  /** the recall-test's running state */
  recallRunning: string
  /** the entry that opens the scope settings where they already live */
  scopeSettings: string
  /** dialog buttons */
  cancel: string
  remove2: string
}

